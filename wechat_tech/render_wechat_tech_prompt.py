from __future__ import annotations

import argparse
import json
import logging
import re
from pathlib import Path

LOGGER = logging.getLogger("render_wechat_tech_prompt")
PLACEHOLDER_STRUCTURED_PAYLOAD = "{{structured_news_payload}}"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Render structured tech news JSON into final prompt text for OpenClaw."
    )
    parser.add_argument(
        "--input-json",
        type=Path,
        required=True,
        help="Structured JSON file generated by the cleaner.",
    )
    parser.add_argument(
        "--prompt-template",
        type=Path,
        default=Path(__file__).with_name("wechat-tech-daily.md"),
        help="Prompt template markdown file.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Output path for rendered prompt text.",
    )
    parser.add_argument(
        "--full-doc",
        action="store_true",
        help="Render the whole markdown document instead of extracting only the prompt code block.",
    )
    parser.add_argument(
        "--compact-json",
        action="store_true",
        help="Render payload JSON in compact form instead of pretty printed form.",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable debug logging.",
    )
    return parser.parse_args()


def setup_logging(verbose: bool) -> None:
    logging.basicConfig(
        level=logging.DEBUG if verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )


def load_json(json_path: Path) -> dict:
    return json.loads(json_path.read_text(encoding="utf-8"))


def load_template(template_path: Path, full_doc: bool) -> str:
    template_text = template_path.read_text(encoding="utf-8")
    if full_doc:
        return template_text
    return extract_prompt_block(template_text)


def extract_prompt_block(template_text: str) -> str:
    section_pattern = re.compile(
        r"##\s+提示词正文\s*\n\s*```(?:md|markdown)?\n(?P<body>[\s\S]*?)\n```",
        flags=re.IGNORECASE,
    )
    match = section_pattern.search(template_text)
    if match:
        return match.group("body").strip() + "\n"

    generic_pattern = re.compile(r"```(?:md|markdown)?\n(?P<body>[\s\S]*?)\n```")
    generic_match = generic_pattern.search(template_text)
    if generic_match:
        return generic_match.group("body").strip() + "\n"

    raise ValueError("No fenced prompt block found in template file.")


def render_payload(payload: dict, compact_json: bool) -> str:
    if compact_json:
        return json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    return json.dumps(payload, ensure_ascii=False, indent=2)


def render_prompt(template_text: str, payload_text: str) -> str:
    if PLACEHOLDER_STRUCTURED_PAYLOAD not in template_text:
        raise ValueError(f"Placeholder not found: {PLACEHOLDER_STRUCTURED_PAYLOAD}")
    return template_text.replace(PLACEHOLDER_STRUCTURED_PAYLOAD, payload_text)


def write_output(output_path: Path, content: str) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")


def main() -> int:
    args = parse_args()
    setup_logging(args.verbose)

    payload = load_json(args.input_json)
    template_text = load_template(args.prompt_template, full_doc=args.full_doc)
    payload_text = render_payload(payload, compact_json=args.compact_json)
    rendered = render_prompt(template_text, payload_text)
    write_output(args.output, rendered)

    LOGGER.info("rendered prompt written to %s", args.output)
    LOGGER.info("template source: %s", args.prompt_template)
    LOGGER.info("payload source: %s", args.input_json)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())